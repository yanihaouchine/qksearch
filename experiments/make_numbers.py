from __future__ import annotations

import json
import math
import os

import numpy as np
from scipy.stats import spearmanr

from experiments import common

OUT = os.path.join(common.REPO_DIR, "report", "numbers.tex")
OUT_TABLE = os.path.join(common.REPO_DIR, "report", "table1.tex")

ORDER = ["quantum-kta", "quantum-dla", "quantum-var", "rbf-kta", "rbf-cv", "linear"]
TABLE_LABELS = {
    "quantum-kta": r"IQP, objective KTA",
    "quantum-dla": r"IQP, objective KTA $-\ \lambda\,\overline{\dim}\,\mathfrak{g}$",
    "quantum-var": r"IQP, objective KTA $+\ 4c\,\mathrm{Var}(K)$",
    "rbf-kta": r"RBF, $\gamma$ by KTA (same criterion)",
    "rbf-cv": r"RBF, $\gamma$ by 5-fold CV",
    "linear": r"linear kernel",
}


def sci(x: float, digits: int = 1) -> str:
    if x == 0:
        return "0"
    e = math.floor(math.log10(abs(x)))
    m = x / 10 ** e
    return rf"{m:.{digits}f}\times 10^{{{e}}}"


def main() -> None:
    lines: list[str] = [
        "% Generated by experiments/make_numbers.py — do not edit by hand."]

    def macro(name: str, value: str) -> None:
        lines.append(rf"\newcommand{{\{name}}}{{{value}}}")

    macro("GitHash", common.git_hash()[:12])
    with open(os.path.join(common.RESULTS_DIR, "meta.json")) as f:
        meta = json.load(f)
    total_wall = sum(m["wall_time_s"] for m in meta.values())
    macro("TotalWallMinutes", f"{total_wall / 60:.0f}")

    macro("SpaceTwoFour", str(common.space_size(2, 4)))
    macro("SpaceTwoSix", str(common.space_size(2, 6)))
    macro("SpaceFourFour", str(common.space_size(4, 4)))
    macro("SpaceFourFive", str(common.space_size(4, 5)))
    macro("SpaceFourSix", str(common.space_size(4, 6)))
    macro("SpaceSixSix", f"{common.space_size(6, 6):,}".replace(",", r"\,"))

    e1 = common.read_csv("e1_concentration.csv")
    med = e1.groupby(["n_qubits", "depth_factor"])["var_offdiag"].median()
    macro("EOneVarTwoDeep", f"${sci(med[2, 4])}$")
    macro("EOneVarTwelveDeep", f"${sci(med[12, 4])}$")
    macro("EOneVarTwelveShallow", f"${sci(med[12, 1])}$")
    macro("EOneOrders", f"{math.log10(med[2, 4] / med[12, 4]):.1f}")

    e2 = common.read_csv("e2_depth_trends.csv")
    two = e2[e2["config"] == "2q"]
    per_seed = two.groupby(["seed", "n_gates"])["kta"].mean().unstack()
    mean_by_gates = per_seed.mean(axis=0)
    peak_gates = int(mean_by_gates.idxmax())
    macro("ETwoPeakGates", str(peak_gates))
    macro("ETwoPeakKta", f"{mean_by_gates.max():.3f}")
    macro("ETwoLastKta", f"{mean_by_gates.iloc[-1]:.3f}")
    dla2 = two[two["seed"] == 0].groupby("n_gates")["dla"].mean()
    macro("ETwoDlaSix", f"{dla2.iloc[-1]:.2f}")

    e3 = common.read_csv("e3_expressivity.csv")
    for space, tag in (("sine", "Sine"), ("mof", "Mof")):
        sub = e3[e3["space"] == space]
        macro(f"EThreeRhoExpr{tag}",
              f"{-spearmanr(sub['expr'], sub['r2']).statistic:+.2f}")
        macro(f"EThreeRhoKta{tag}",
              f"{spearmanr(sub['kta'], sub['r2']).statistic:+.2f}")
        best = sub.loc[sub["kta"].idxmax()]
        macro(f"EThreeBestKta{tag}", f"{best['kta']:.3f}")
        macro(f"EThreeBestKtaRTwo{tag}", f"{best['r2']:.3f}")
        macro(f"EThreeBestRTwo{tag}", f"{sub['r2'].max():.3f}")
    worst = e3[e3["space"] == "sine"].loc[lambda d: d["kta"].idxmin()]
    macro("EThreeWorstKtaSine", f"{worst['kta']:.4f}")
    macro("EThreeWorstRTwoSine", f"{worst['r2']:.3f}")
    mof = e3[e3["space"] == "mof"]
    macro("EThreeRhoDlaRTwoMof", f"{spearmanr(mof['dla'], mof['r2']).statistic:+.2f}")
    macro("EThreeRhoVarRTwoMof", f"{spearmanr(mof['var4'], mof['r2']).statistic:+.2f}")

    e2corr = common.read_csv("e6_correlations.csv")
    c2 = e2corr[e2corr["config"] == "2q"]
    macro("ESixRhoKtaDla", f"{c2['rho_kta_dla'].mean():+.2f}")
    macro("ESixRhoKtaDlaStd", f"{c2['rho_kta_dla'].std():.2f}")
    macro("ESixRhoKtaVar", f"{c2['rho_kta_var'].mean():+.2f}")
    macro("ESixRhoKtaVarStd", f"{c2['rho_kta_var'].std():.2f}")

    e4 = common.read_csv("e4_search.csv")
    mcts = e4[e4["strategy"] == "mcts"]
    opt = meta["e4_search"]["params"]["optimum_kta"]
    macro("EFourOptKta", f"{opt:.4f}")

    def at(budget: int, col: str) -> float:
        return mcts[mcts["n_iterations"] == budget][col].mean()

    macro("EFourFracTwoHundred", f"{100 * at(200, 'frac_of_opt'):.0f}")
    macro("EFourEvalsTwoHundred", f"{at(200, 'n_evaluated'):.0f}")
    macro("EFourFracTwoThousand", f"{100 * at(2000, 'frac_of_opt'):.1f}")
    macro("EFourEvalsTwoThousand", f"{at(2000, 'n_evaluated'):.0f}")
    greedy = e4[e4["strategy"] == "greedy"].iloc[0]
    macro("EFourGreedyFrac", f"{100 * greedy['frac_of_opt']:.0f}")
    macro("EFourGreedyEvals", f"{greedy['n_evaluated']:.0f}")

    e5 = common.read_csv("e5_benchmark.csv")

    def stats(dataset: str, method: str) -> dict:
        v = e5[(e5["dataset"] == dataset) & (e5["method"] == method)]["r2_test"]
        k = e5[(e5["dataset"] == dataset) & (e5["method"] == method)]["kta_train"]
        return {"median": v.median(), "q1": v.quantile(0.25),
                "q3": v.quantile(0.75), "min": v.min(), "kta": k.mean()}

    macro("EFiveQKtaSine", f"{stats('sine', 'quantum-kta')['median']:.2f}")
    macro("EFiveRbfCvSine", f"{stats('sine', 'rbf-cv')['median']:.2f}")
    macro("EFiveRbfKtaSine", f"{stats('sine', 'rbf-kta')['median']:.2f}")
    macro("EFiveQKtaMof", f"{stats('mof', 'quantum-kta')['median']:.2f}")
    macro("EFiveRbfCvMof", f"{stats('mof', 'rbf-cv')['median']:.2f}")
    macro("EFiveRbfKtaMof", f"{stats('mof', 'rbf-kta')['median']:.2f}")
    macro("EFiveLinearMof", f"{stats('mof', 'linear')['median']:.2f}")
    macro("EFiveDlaMofMin", f"{stats('mof', 'quantum-dla')['min']:.1f}")
    macro("EFiveQKtaSineTrainKta", f"{stats('sine', 'quantum-kta')['kta']:.3f}")

    with open(OUT_TABLE, "w") as f:
        f.write("% Generated by experiments/make_numbers.py.\n")
        f.write("\\begin{tabular}{lcccc}\n\\toprule\n")
        f.write("kernel & \\multicolumn{2}{c}{synthetic sine} & "
                "\\multicolumn{2}{c}{MOF H$_2$ uptake} \\\\\n")
        f.write("\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\n")
        f.write(" & KTA & test $R^2$ & KTA & test $R^2$ \\\\\n\\midrule\n")
        for m in ORDER:
            s, o = stats("sine", m), stats("mof", m)
            f.write(f"{TABLE_LABELS[m]} & {s['kta']:.2f} & "
                    f"{s['median']:+.2f} [{s['q1']:+.2f}, {s['q3']:+.2f}] & "
                    f"{o['kta']:.2f} & "
                    f"{o['median']:+.2f} [{o['q1']:+.2f}, {o['q3']:+.2f}] \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")
    print(f"table → {OUT_TABLE}")

    e6 = common.read_csv("e6_tradeoff.csv")

    def winner(space: str, reg: str, weight: float) -> dict:
        m = e6[(e6["space"] == space) & (e6["regularizer"] == reg)
               & (np.isclose(e6["weight"], weight))]
        return m.iloc[0].to_dict()

    macro("ESixSineBaseRTwo", f"{winner('sine', 'dla', 0.0)['winner_r2']:.3f}")
    macro("ESixSineDlaFlipRTwo", f"{winner('sine', 'dla', 1.0)['winner_r2']:.3f}")
    macro("ESixSineVarFlipRTwo",
          f"{winner('sine', 'variance', 1.0)['winner_r2']:.3f}")
    macro("ESixMofBaseRTwo", f"{winner('mof', 'dla', 0.0)['winner_r2']:.3f}")
    macro("ESixMofVarFlipRTwo",
          f"{winner('mof', 'variance', 0.5)['winner_r2']:.3f}")

    def tipping(space: str, reg: str) -> float:
        sub = e6[(e6["space"] == space) & (e6["regularizer"] == reg)]
        sub = sub.sort_values("weight")
        base = sub.iloc[0]["winner_id"]
        changed = sub[sub["winner_id"] != base]
        return float(changed.iloc[0]["weight"]) if len(changed) else float("inf")

    macro("ESixTipLambdaSine", f"{tipping('sine', 'dla'):g}")
    macro("ESixTipCSine", f"{tipping('sine', 'variance'):g}")
    macro("ESixTipCMof", f"{tipping('mof', 'variance'):g}")

    e9 = common.read_csv("e9_ablation.csv")
    med9 = e9.groupby("variant")["r2_cv"].median()
    macro("ENineRbfCvAll", f"{med9['all']:.2f}")
    macro("ENineRbfCvNoVol", f"{med9['no_x1']:.2f}")
    macro("ENineRbfCvNoBet", f"{med9['no_x0']:.2f}")
    macro("ENineRbfCvNoPres", f"{med9['no_x2']:.2f}")
    base = e9[e9["variant"] == "all"].set_index("seed")["r2_cv"]
    novol = e9[e9["variant"] == "no_x1"].set_index("seed")["r2_cv"]
    macro("ENineNoVolWins", str(int((novol > base).sum())))
    m9 = meta["e9_feature_ablation"]["params"]
    macro("ENineCorrBetVol", f"{m9['corr_bet_vol']:.2f}")
    macro("ENineSearches", str(m9["quantum_searches"]))
    macro("ENineUsageVol", str(m9["feature_usage"]["x1"]))
    macro("ENineDropVol",
          str(m9["quantum_searches"] - m9["feature_usage"]["x1"]))
    macro("ENineUsagePres", str(m9["feature_usage"]["x2"]))

    e7 = common.read_csv("e7_geometry.csv")
    macro("ESevenGeomMax", f"{e7['geom'].max():.1f}")
    macro("ESevenGeomLast", f"{e7['geom'].iloc[-1]:.1f}")
    macro("ESevenSqrtLast", f"{e7['sqrt_n'].iloc[-1]:.1f}")

    e11 = common.read_csv("e11_best.csv")
    valid = e11[e11["mode"] == "valid_r1"]
    macro("ElevenSeeds", str(len(valid)))
    macro("ElevenHits", str(int((valid["frac_of_opt"] >= 1 - 1e-9).sum())))
    macro("ElevenEvals", f"{valid['n_evaluated'].median():.0f}")
    macro("ElevenWorstFrac", f"{100 * valid['frac_of_opt'].min():.2f}")
    for mode, tag in (("valid_r1", "One"), ("prod_r2", "Two"),
                      ("prod_r2_phase", "Phase")):
        sub = e11[e11["mode"] == mode]
        macro(f"ElevenKta{tag}", f"{sub['kta_train'].median():.3f}")
        macro(f"ElevenRTwo{tag}", f"{sub['r2_test'].median():+.3f}")
        macro(f"ElevenGates{tag}", f"{sub['support'].median():.1f}")
    phase = e11[e11["mode"] == "prod_r2_phase"]
    macro("ElevenPhaseKept", str(int((phase["n_phase_gates"] > 0).sum())))
    worst = e11.loc[e11["r2_test"].idxmin()]
    macro("ElevenWorstRTwo", f"{worst['r2_test']:+.3f}")
    macro("ElevenWorstRTwoKta", f"{worst['kta_train']:.3f}")
    m11 = meta["e11_genetic"]["params"]
    macro("ElevenPopulation", str(m11["population_size"]))
    macro("ElevenHarvested", str(m11["n_harvested"]))
    macro("ElevenRandom", str(m11["population_size"] - m11["n_harvested"]))

    from qksearch.genome import iqp_genome_spec
    spec = iqp_genome_spec(4, 4, n_layers=2, phases=("t", "cs"))
    macro("ElevenGenes", str(len(spec.genes)))
    macro("ElevenBits", str(spec.n_bits))
    macro("ElevenSpace", f"${sci(2.0 ** spec.n_bits)}$")

    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"macros → {OUT} ({len(lines) - 1} macros)")


if __name__ == "__main__":
    main()
